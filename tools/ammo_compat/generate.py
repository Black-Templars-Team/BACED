#!/usr/bin/env python3
"""Generate BACED's per-mod ammo compatibility addons."""

import heapq
import json
from pathlib import Path
import re
import shutil


TOOL_DIR = Path(__file__).resolve().parent
ADDONS_DIR = TOOL_DIR.parents[1] / "addons"
GENERATED = "// Generated by tools/ammo_compat/generate.py from ammo_map.json; do not edit by hand."


def render_ammo(entries):
    by_class = {entry["class"].casefold(): entry for entry in entries}
    if len(by_class) != len(entries):
        raise ValueError("duplicate ammo class (case-insensitive)")

    external_parents = {}
    children = {name: [] for name in by_class}
    ready = []
    for name, entry in sorted(by_class.items()):
        parent = entry["parent"].casefold()
        if parent in by_class:
            children[parent].append(name)
        else:
            external_parents.setdefault(parent, entry["parent"])
            ready.append(name)

    lines = [GENERATED, "", "class CfgAmmo {"]
    for parent in sorted(external_parents):
        lines.append(f"    class {external_parents[parent]};")
    if external_parents and entries:
        lines.append("")

    # Alphabetical among classes whose parents are already available.
    heapq.heapify(ready)
    emitted = 0
    while ready:
        name = heapq.heappop(ready)
        entry = by_class[name]
        lines.extend([
            f'    class {entry["class"]}: {entry["parent"]} {{',
            f'        ACE_damageType = "{entry["damageType"]}";',
            "    };",
        ])
        emitted += 1
        for child in children[name]:
            heapq.heappush(ready, child)

    if emitted != len(entries):
        raise ValueError("cycle in ammo class inheritance")
    return "\n".join([*lines, "};", ""])


def render_addon(component, mod):
    # Punctuation in the mod name can break COMPONENT_NAME's QUOTE expansion.
    name = " ".join(re.sub(r"[^A-Za-z0-9 ]", "", mod["name"]).split())
    dependencies = [
        "baced_medical",
        *(f"baced_compat_{slug}" for slug in mod["after"]),
        *mod["requiredAddons"],
    ]
    dependency_lines = ",\n".join(f"            {json.dumps(dep)}" for dep in dependencies)

    return {
        "$PBOPREFIX$": rf"z\baced\addons\{component}",
        "script_component.hpp": rf'''{GENERATED}

#define COMPONENT {component}
#define COMPONENT_BEAUTIFIED Compat - {name}
#include "\z\baced\addons\main\script_mod.hpp"
#include "\z\baced\addons\main\script_macros.hpp"
''',
        "config.cpp": f'''{GENERATED}

#include "script_component.hpp"

class CfgPatches {{
    class ADDON {{
        name = COMPONENT_NAME;
        units[] = {{}};
        weapons[] = {{}};
        requiredVersion = REQUIRED_VERSION;
        requiredAddons[] = {{
{dependency_lines}
        }};
        skipWhenMissingDependencies = 1;
        author = "BACED Team";
        url = "https://github.com/Black-Templars-Team/BACED";
        VERSION_CONFIG;
    }};
}};

#include "CfgAmmo.hpp"
''',
        "CfgAmmo.hpp": render_ammo(mod["ammo"]),
    }


def main():
    with (TOOL_DIR / "ammo_map.json").open(encoding="utf-8") as source:
        mods = json.load(source)["mods"]

    outputs = {}
    # Check all targets and render everything before replacing any directories.
    for mod in mods:
        slug = mod["slug"]
        if not re.fullmatch(r"[a-z0-9_]+", slug):
            raise ValueError(f"invalid mod slug: {slug!r}")
        target = ADDONS_DIR / f"compat_{slug}"
        if target in outputs:
            raise ValueError(f"duplicate mod slug: {slug}")
        if target.is_symlink() or (target.exists() and not target.is_dir()):
            raise ValueError(f"expected an addon directory: {target}")
        try:
            outputs[target] = render_addon(target.name, mod)
        except ValueError as error:
            raise ValueError(f"{slug}: {error}") from error

    for target, files in outputs.items():
        if target.exists():
            shutil.rmtree(target)
        target.mkdir()
        for filename, content in files.items():
            (target / filename).write_bytes(content.encode("utf-8"))

    print(f"Generated {len(outputs)} ammo compatibility addons.")


if __name__ == "__main__":
    main()
