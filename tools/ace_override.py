#!/usr/bin/env python3
"""Manage BACED's overrides of ACE3 functions.

BACED is loaded alongside ACE3 and replaces individual ACE functions with its own copies.
ACE's source is read from a git ref (default: master, the upstream ACE3 mirror branch).

  add <component> <function>   Copy an ACE function into BACED and register it as an override
                               e.g. add medical_treatment canBandage
  remove <component> <function> Delete an override so ACE's original is used again
  check                       Report overridden functions that changed in ACE since they were copied
  sync-headers                 Refresh ACE's headers in include/z/ace (needed to build the overrides)

How an override works:
  addons/<addon>/ace_<component>/ holds the copies. They are compiled with that ACE component's own
  script_component.hpp, so GVAR/FUNC/QPATHTOF in copied code still refer to ACE. BACED's config
  replaces ACE's XEH preStart/preInit entries for the component so BACED's copies are compiled first;
  CBA_fnc_compileFunction then uses them from the cache instead of ACE's files.
"""

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADDONS = ROOT / "addons"
ACE_INCLUDE = ROOT / "include" / "z" / "ace" / "addons"

HEADER_RE = re.compile(r"^// BACED override of (\S+) - copied from ACE3 ([0-9a-f]{40})")
ACE_INCLUDE_RE = re.compile(r'#include\s+"\\z\\ace\\addons\\([^\\"]+)\\([^"]+)"')
XEH_EVENTS = ("XEH_preStart", "XEH_preInit")


def git(*args, check=True):
    result = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    if check and result.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed:\n{result.stderr.strip()}")
    return result


def ace_file(ref, path):
    """Return the content of an ACE file at ref, or None if it does not exist."""
    result = git("show", f"{ref}:{path}", check=False)
    return result.stdout if result.returncode == 0 else None


def override_dirs():
    """Yield (addon, component, path) for every addons/<addon>/ace_<component> folder."""
    for path in sorted(ADDONS.glob("*/ace_*")):
        if path.is_dir():
            yield path.parent.name, path.name[len("ace_"):], path


def check_hookable(ref, component):
    """BACED replaces ACE's XEH init strings, so they must still be the standard ones."""
    cfg = ace_file(ref, f"addons/{component}/CfgEventHandlers.hpp") or ""
    missing = [e for e in XEH_EVENTS if f"init = QUOTE(call COMPILE_SCRIPT({e}));" not in cfg]
    if missing:
        return f"ACE's {component} XEH entries changed or are missing ({', '.join(missing)}); update ACE_XEH_HOOK"
    return None


def write_if_missing(path, content):
    if not path.exists():
        path.write_text(content, newline="\n")


def scaffold(addon, component):
    folder = ADDONS / addon / f"ace_{component}"
    (folder / "functions").mkdir(parents=True, exist_ok=True)
    write_if_missing(folder / "script_component.hpp", (
        f"// Overrides of ACE3's {component} functions, compiled with ACE's own macros\n"
        f"#include \"\\z\\ace\\addons\\{component}\\script_component.hpp\"\n"
        "#include \"\\z\\baced\\addons\\main\\script_override.hpp\"\n"
        "\n"
        f"#define OVERRIDE_PATH \\z\\baced\\addons\\{addon}\\ace_{component}\n"
    ))
    write_if_missing(folder / "XEH_PREP.hpp", f"// ACE {component} functions replaced by BACED (see tools/ace_override.py)\n")
    write_if_missing(folder / "XEH_overrides.sqf", (
        "#include \"script_component.hpp\"\n"
        f"// Runs right before ACE's own {component} XEH_preStart/XEH_preInit (see ACE_XEH_HOOK)\n"
        "\n"
        "#include \"XEH_PREP.hpp\"\n"
    ))
    return folder


def regenerate_hooks(addon):
    components = [c for a, c, _ in override_dirs() if a == addon]
    lines = ["// Generated by tools/ace_override.py - one HOOK line per ACE component this addon overrides functions of."]
    lines += [f"HOOK({c});" for c in components]
    (ADDONS / addon / "ace_overrides.hpp").write_text("\n".join(lines) + "\n", newline="\n")


def cmd_add(args):
    component = args.component.removeprefix("ace_")
    function = args.function.removeprefix("fnc_").removesuffix(".sqf")
    addon = args.addon or component.split("_")[0]
    if not (ADDONS / addon / "config.cpp").exists():
        sys.exit(f"BACED addon '{addon}' does not exist; pass --addon")

    source_path = f"addons/{component}/functions/fnc_{function}.sqf"
    source = ace_file(args.ref, source_path)
    if source is None:
        sys.exit(f"{source_path} not found in {args.ref}")
    problem = check_hookable(args.ref, component)
    if problem:
        sys.exit(problem)

    folder = scaffold(addon, component)
    target = folder / "functions" / f"fnc_{function}.sqf"
    if target.exists() and not args.force:
        sys.exit(f"{target.relative_to(ROOT)} already exists; pass --force to overwrite it")

    sha = git("rev-parse", args.ref).stdout.strip()
    target.write_text(f"// BACED override of ace_{component}_fnc_{function} - copied from ACE3 {sha}\n{source}", newline="\n")

    prep = folder / "XEH_PREP.hpp"
    line = f"OVERRIDE({function});"
    if line not in prep.read_text().splitlines():
        with prep.open("a", newline="\n") as f:
            f.write(line + "\n")

    regenerate_hooks(addon)
    if f'"ace_{component}"' not in (ADDONS / addon / "config.cpp").read_text():
        print(f"warning: add \"ace_{component}\" to requiredAddons in addons/{addon}/config.cpp", file=sys.stderr)
    sync_headers(args.ref)
    print(f"Copied {source_path} ({sha[:9]}) to {target.relative_to(ROOT)}")


def cmd_remove(args):
    component = args.component.removeprefix("ace_")
    function = args.function.removeprefix("fnc_").removesuffix(".sqf")
    matches = [(a, f) for a, c, f in override_dirs() if c == component and (f / "functions" / f"fnc_{function}.sqf").exists()]
    if not matches:
        sys.exit(f"No BACED override of ace_{component}_fnc_{function}")
    addon, folder = matches[0]
    (folder / "functions" / f"fnc_{function}.sqf").unlink()
    prep = folder / "XEH_PREP.hpp"
    prep.write_text("".join(l for l in prep.read_text().splitlines(True) if l.strip() != f"OVERRIDE({function});"), newline="\n")
    if not any((folder / "functions").glob("fnc_*.sqf")):
        shutil.rmtree(folder)
        print(f"Removed {folder.relative_to(ROOT)} (no overrides left), ACE's {component} XEH entries are no longer hooked")
    regenerate_hooks(addon)
    sync_headers(args.ref)
    print(f"Removed override of ace_{component}_fnc_{function}")


def cmd_check(args):
    changed = 0
    for addon, component, folder in override_dirs():
        problem = check_hookable(args.ref, component)
        if problem:
            print(problem)
            changed += 1
        for path in sorted((folder / "functions").glob("fnc_*.sqf")):
            match = HEADER_RE.match(path.read_text().split("\n", 1)[0])
            if not match:
                print(f"{path.relative_to(ROOT)}: missing BACED override header, cannot check")
                changed += 1
                continue
            source = f"addons/{component}/functions/{path.name}"
            if git("diff", "--quiet", match[2], args.ref, "--", source, check=False).returncode != 0:
                print(f"{path.relative_to(ROOT)}: ACE changed it since {match[2][:9]}\n"
                      f"    git diff {match[2][:9]} {args.ref} -- {source}")
                changed += 1
    print("All overrides are up to date with ACE." if not changed else f"{changed} override(s) need attention.")
    return 1 if changed else 0


def sync_headers(ref):
    """Copy the script_*.hpp headers of ACE main, every overridden component and anything they include."""
    pending = {"main"} | {c for _, c, _ in override_dirs()}
    done = set()
    files = {}
    while pending:
        component = pending.pop()
        done.add(component)
        listing = git("ls-tree", "--name-only", f"{ref}:addons/{component}", check=False).stdout.split()
        for name in listing:
            if name.startswith("script_") and name.endswith(".hpp"):
                content = ace_file(ref, f"addons/{component}/{name}")
                files[(component, name)] = content
                for included, _ in ACE_INCLUDE_RE.findall(content):
                    if included not in done:
                        pending.add(included)

    if ACE_INCLUDE.exists():
        shutil.rmtree(ACE_INCLUDE)
    for (component, name), content in files.items():
        path = ACE_INCLUDE / component / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, newline="\n")
    print(f"Synced {len(files)} ACE header(s) from {ref} into {ACE_INCLUDE.relative_to(ROOT)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ref", default="master", help="git ref holding the ACE3 source (default: master)")
    sub = parser.add_subparsers(dest="command", required=True)

    add = sub.add_parser("add", help="copy an ACE function into BACED as an override")
    add.add_argument("component", help="ACE component, e.g. medical_treatment")
    add.add_argument("function", help="function name, e.g. canBandage")
    add.add_argument("--addon", help="BACED addon to put it in (default: first part of the component, e.g. medical)")
    add.add_argument("--force", action="store_true", help="overwrite an existing override")

    remove = sub.add_parser("remove", help="delete an override so ACE's original is used again")
    remove.add_argument("component", help="ACE component, e.g. medical_treatment")
    remove.add_argument("function", help="function name, e.g. canBandage")

    sub.add_parser("check", help="report overrides whose ACE original changed")
    sub.add_parser("sync-headers", help="refresh ACE headers in include/z/ace")

    args = parser.parse_args()
    if args.command == "add":
        cmd_add(args)
    elif args.command == "remove":
        cmd_remove(args)
    elif args.command == "check":
        sys.exit(cmd_check(args))
    else:
        sync_headers(args.ref)


if __name__ == "__main__":
    main()
